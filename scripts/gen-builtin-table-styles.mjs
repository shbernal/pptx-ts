#!/usr/bin/env node
/**
 * Extract PowerPoint's definitions of the 74 built-in table styles into
 * `src/gen/pres/builtin-table-styles.ts`.
 *
 * The source is `test/read/fixtures/table-styles-builtin.pptx`, a deck PowerPoint saved with one
 * table per built-in style (`test/read/fixtures/authoring/author-table-styles-builtin.ps1`). Saving
 * it made PowerPoint write every style's `a:tblStyle` into `ppt/tableStyles.xml`, so the module
 * carries PowerPoint's own markup and nothing written by hand.
 *
 * **Stored as templates.** The 74 definitions are 160 KB of XML, about 6 KB gzipped, which is more
 * than the bundle budget has room for. They are also mostly repeats: each "- Accent N" style is its
 * family's Accent 1 definition with `accent1` swapped for `accentN`, and several of the plain
 * styles are the same body with `dk1` or `tx1` in the accent's place. So each family's Accent 1
 * body is stored once with `$0` (and `$1` for the two-accent Dark Style 2) where the accent was,
 * and each style names its template and the values that fill it. A style no template reproduces
 * byte for byte is stored whole as its own body. The expansion is checked against the fixture in
 * `test/scripts/gen-builtin-table-styles.test.ts`, so a template that fails to round-trip fails
 * there rather than shipping.
 *
 *   node scripts/gen-builtin-table-styles.mjs            # rewrite the module
 *   node scripts/gen-builtin-table-styles.mjs --check    # exit 1 if the module is not what this would write
 */

import fs from 'node:fs'
import path from 'node:path'
import { strFromU8, unzipSync } from 'fflate'
import { ROOT, isMain, parseCliOrExit } from './script-utils.mjs'

/** The module this writes. */
export const MODULE_PATH = path.join(ROOT, 'src', 'gen', 'pres', 'builtin-table-styles.ts')

/** The PowerPoint-authored deck the definitions come from. */
export const FIXTURE_PATH = path.join(ROOT, 'test', 'read', 'fixtures', 'table-styles-builtin.pptx')

/** The scheme colours a template slot may take. */
const SLOT_VALUES = ['accent1', 'accent2', 'accent3', 'accent4', 'accent5', 'accent6', 'dk1', 'tx1', 'lt1']

/**
 * Every `a:tblStyle` in the fixture's `ppt/tableStyles.xml`, in the order PowerPoint wrote them.
 * @returns {{ styleId: string, styleName: string, body: string }[]}
 */
export function fixtureStyles() {
	const part = unzipSync(fs.readFileSync(FIXTURE_PATH), { filter: (f) => f.name === 'ppt/tableStyles.xml' })[
		'ppt/tableStyles.xml'
	]
	if (!part) throw new Error(`${FIXTURE_PATH} has no ppt/tableStyles.xml`)
	const xml = strFromU8(part)
	return [...xml.matchAll(/<a:tblStyle styleId="([^"]+)" styleName="([^"]+)">([\s\S]*?)<\/a:tblStyle>/g)].map((m) => ({
		styleId: m[1] ?? '',
		styleName: m[2] ?? '',
		body: m[3] ?? '',
	}))
}

/**
 * Fill a template's `$0`/`$1` slots.
 * @param {string} template
 * @param {readonly string[]} args
 */
export function expand(template, args) {
	return template.replace(/\$(\d)/g, (_, /** @type {string} */ i) => args[Number(i)] ?? '')
}

/**
 * The templates and the per-style rows that reproduce every fixture style.
 * @returns {{ bodies: string[], rows: [string, string, number, ...string[]][] }}
 */
export function buildCatalogue() {
	const styles = fixtureStyles()
	/** @type {string[]} */
	const bodies = []
	for (const s of styles) {
		if (s.styleName.endsWith(' - Accent 1/Accent 2')) {
			bodies.push(s.body.replaceAll('accent1', '$0').replaceAll('accent2', '$1'))
		} else if (s.styleName.endsWith(' - Accent 1')) {
			bodies.push(s.body.replaceAll('accent1', '$0'))
		}
	}
	/** @type {[string, string, number, ...string[]][]} */
	const rows = []
	for (const s of styles) {
		/** @type {[string, string, number, ...string[]] | null} */
		let row = null
		for (const [i, template] of bodies.entries()) {
			if (row) break
			for (const [k, a] of SLOT_VALUES.entries()) {
				const next = SLOT_VALUES[k + 1]
				/** @type {string[] | null} */
				const args = !template.includes('$1') ? [a] : next ? [a, next] : null
				if (args && expand(template, args) === s.body) {
					row = [s.styleId, s.styleName, i, ...args]
					break
				}
			}
		}
		if (!row) {
			bodies.push(s.body)
			row = [s.styleId, s.styleName, bodies.length - 1]
		}
		rows.push(row)
	}
	return { bodies, rows }
}

/** The module source. */
export function builtinTableStylesModule() {
	const { bodies, rows } = buildCatalogue()
	const q = (/** @type {string} */ s) => `'${s}'`
	return `/**
 * pptx-ts: the built-in table style definitions
 *
 * GENERATED by \`scripts/gen-builtin-table-styles.mjs\` from \`test/read/fixtures/table-styles-builtin.pptx\`.
 * Do not edit by hand: re-run the script.
 *
 * PowerPoint's own \`a:tblStyle\` markup for the 74 built-in [MS-OE376] table styles, which it
 * writes into \`ppt/tableStyles.xml\` for every style a deck uses. Each body is a template whose
 * \`$0\`/\`$1\` slots take the scheme colour that varies across a family's accent variants; see the
 * script's header for why.
 */

import { el, raw } from '../oxml/el.js'

/**
 * Style bodies, the children of \`a:tblStyle\`, with \`$0\`/\`$1\` where a family's accent goes.
 * @raw-xml-asset Captured verbatim from PowerPoint; not built here, so not a migration target.
 */
const BODIES: readonly string[] = [
${bodies.map((b) => `\t${q(b)},`).join('\n')}
]

/** \`[styleId, styleName, body index, ...slot values]\`, in the order PowerPoint wrote them. */
const STYLES: readonly (readonly [string, string, number, ...string[]])[] = [
${rows.map(([id, name, i, ...args]) => `\t[${[q(id), q(name), String(i), ...args.map(q)].join(', ')}],`).join('\n')}
]

/**
 * The \`a:tblStyle\` element PowerPoint writes for the built-in style \`styleId\`, or \`undefined\`
 * when \`styleId\` is not one of the 74 built-in styles.
 */
export function builtinTableStyleXml(styleId: string): string | undefined {
	const row = STYLES.find((s) => s[0] === styleId)
	if (!row) return undefined
	const [, styleName, index, ...args] = row
	const body = BODIES[index]?.replace(/\\$(\\d)/g, (_, i: string) => args[Number(i)] ?? '') ?? ''
	return el('a:tblStyle', { styleId, styleName }, raw(body))
}
`
}

if (isMain(import.meta.url)) {
	const { values } = parseCliOrExit(process.argv.slice(2), {
		options: { check: { type: 'boolean', default: false } },
		usage: 'usage: node scripts/gen-builtin-table-styles.mjs [--check]',
	})
	const source = builtinTableStylesModule()
	const rel = path.relative(ROOT, MODULE_PATH)
	if (values.check) {
		if (fs.readFileSync(MODULE_PATH, 'utf8') === source) console.log(`${rel} is up to date`)
		else {
			console.error(`${rel} differs from what gen-builtin-table-styles.mjs writes`)
			process.exit(1)
		}
	} else {
		fs.writeFileSync(MODULE_PATH, source)
		const { bodies, rows } = buildCatalogue()
		console.log(`wrote ${rel}: ${rows.length} styles from ${bodies.length} bodies, ${source.length} bytes`)
	}
}
